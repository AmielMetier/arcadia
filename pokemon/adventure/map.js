export function isSolid(grid, tx, ty) {
  if (!grid || ty < 0 || ty >= grid.length || tx < 0 || tx >= grid[0].length) {
    return true;
  }
  return SOLID_TILES.has(grid[ty][tx]);
}

export function getTile(grid, tx, ty) {
  if (!grid || ty < 0 || ty >= grid.length || tx < 0 || tx >= grid[0].length) {
    return TILE.TREE_PINE;
  }
  return grid[ty][tx];
}
